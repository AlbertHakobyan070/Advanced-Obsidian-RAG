"""Graph assembly: merge duplicates, enforce the caps, build map.json, render the canvas.

Pure Python, no LLM, no network. The map dict follows spec section 6; the canvas is
JSON Canvas 1.0, laid out deterministically (groups on a 3-column grid, layers inside).
"""
import re
import textwrap

import networkx as nx

from src.ingestion.canvas_edit import merge_canvas
from src.utils.provenance import marks_generated_canvas

from .config import KMConfig
from .graph import Edge, Node, edge_id, slug
from .locate import format_pages, page_ranges
from .scout import Scout
from .templates import Template

QUOTE_CAP = 3            # quotes kept per node
BODY_MAX = 1500          # canvas text node body, spec section 6
TITLE_MAX = 80
SUMMARY_SENTENCES = 3
SUMMARY_FLOOR = 200      # the summary is cut to this before a later quote is dropped
NAME_MAX = 150
NAME_SUFFIX = " (generated).canvas"
_ILLEGAL = re.compile(r'[<>:"/\\|?*\x00-\x1f]')

# Canvas geometry (pixels). Node height comes from the text length: fixed width, line count.
NODE_W, LINE_H, CHARS_PER_LINE, PAD = 320, 24, 38, 30
GAP = 40
GRID_COLS = 3            # groups per grid row, and nodes per row inside a group
GROUP_HEAD = 60
GROUP_W = GRID_COLS * NODE_W + (GRID_COLS + 1) * GAP
FILE_H = 240


def merge_nodes(nodes: list[Node]) -> list[Node]:
    """Nodes with the same slug(title) (so the same id) become one: the first node's id, kind, section and unit,
    the union of quotes (first QUOTE_CAP), the highest importance."""
    merged: dict[str, Node] = {}
    for n in nodes:
        m = merged.get(slug(n.title))
        if m is None:
            merged[slug(n.title)] = Node(**{**n.__dict__, "quotes": list(n.quotes), "located": list(n.located)})
            continue
        m.quotes = list(dict.fromkeys(m.quotes + n.quotes))[:QUOTE_CAP]
        seen = {q for q, _ in m.located}
        m.located = (m.located + [(q, p) for q, p in n.located if q not in seen])[:QUOTE_CAP]
        m.importance = max(m.importance, n.importance)
    return list(merged.values())


def _section_no(section_id: str) -> int:
    m = re.fullmatch(r"sec-(\d+)", section_id)
    if not m:
        raise ValueError(f"section id '{section_id}' is not of the form sec-<n>")
    return int(m.group(1))


def apply_caps(nodes: list[Node], edges: list[Edge], kcfg: KMConfig) -> tuple[list[Node], list[Edge], list[dict]]:
    """Hard node cap, then per-node fan-out. Returns (nodes, edges, rejects)."""
    rejects: list[dict] = []
    known = {n.id for n in nodes}
    for e in edges:      # an endpoint that was never a node is a caller bug; edges to nodes cut below just go
        for end in (e.source, e.target):
            if end not in known:
                raise ValueError(f"edge '{e.id}' has endpoint '{end}', which is not in the node list")
    if len(nodes) > kcfg.node_cap:
        order = sorted(range(len(nodes)), key=lambda i: (-nodes[i].importance, _section_no(nodes[i].section), i))
        keep = set(order[:kcfg.node_cap])
        rejects += [{"id": n.id, "title": n.title, "reason": "cap"} for i, n in enumerate(nodes) if i not in keep]
        nodes = [n for i, n in enumerate(nodes) if i in keep]
    imp = {n.id: n.importance for n in nodes}
    edges = [e for e in edges if e.source in imp and e.target in imp]

    drop: set[str] = set()
    for nid in imp:
        mine = sorted((e for e in edges if nid in (e.source, e.target)),
                      key=lambda e: (e.status != "stated", -imp[e.target if e.source == nid else e.source], e.id))
        drop.update(e.id for e in mine[kcfg.fanout_max:])
    rejects += [{"id": e.id, "title": f"{e.source} -[{e.type}]-> {e.target}", "reason": "fanout"}
                for e in edges if e.id in drop]
    return nodes, [e for e in edges if e.id not in drop], rejects


def canvas_name(book_title: str, chapter_title: str, markers: tuple[str, ...]) -> str:
    """`markers` is KMConfig.generated_markers: the name must mark the canvas generated
    under the same canvas.generated_markers the canvas lane reads."""
    base = " ".join(_ILLEGAL.sub("-", f"{book_title} - {chapter_title}").split())
    name = base[:NAME_MAX - len(NAME_SUFFIX)].rstrip(" .") + NAME_SUFFIX
    if not marks_generated_canvas(name, markers):
        raise ValueError(f"canvas name '{name}' is not marked generated by canvas.generated_markers {list(markers)}")
    return name


def _quote(text: str, pages) -> dict:
    return {"text": text, "pages": list(pages)}


def build_map(scout: Scout, template: Template, reason: str, nodes: list[Node], edges: list[Edge],
              markers: tuple[str, ...]) -> dict:
    """The map.json dict (spec section 6) with hub nodes and structural part-of edges."""
    sec_ids = {s.id for s in scout.sections}
    ids: dict[str, str] = {}
    for n in nodes:
        if n.id in ids:
            raise ValueError(f"duplicate node id '{n.id}': '{ids[n.id]}' and '{n.title}'")
        ids[n.id] = n.title
    out_nodes = [{"id": "chapter", "kind": "hub", "title": scout.chapter_title,
                  "summary": " ".join(template.purpose.split()), "quotes": [],
                  "source_pages": [[scout.page_start, scout.page_end]]}]
    out_nodes += [{"id": s.id, "kind": "hub", "title": s.title, "summary": "", "quotes": [],
                   "source_pages": [[s.page_start, s.page_end]]} for s in scout.sections]
    for n in nodes:
        if n.section not in sec_ids:
            raise ValueError(f"node '{n.id}' is in section '{n.section}', which the scout did not produce")
        if not n.located:
            raise ValueError(f"node '{n.id}' has no located quote: every kept node needs a verbatim, located quote")
        out_nodes.append({"id": n.id, "kind": n.kind, "title": n.title, "summary": n.summary,
                          "section": n.section, "importance": n.importance,
                          "quotes": [_quote(q, p) for q, p in n.located],
                          "source_pages": [list(r) for r in page_ranges(p for _, ps in n.located for p in ps)],
                          **({"summary_revised_from": n.summary_revised_from} if n.summary_revised_from else {})})
    out_edges = []
    for e in edges:
        if e.source not in ids or e.target not in ids:
            raise ValueError(f"edge '{e.id}' ({e.source} -> {e.target}) points at a node that is not in the graph")
        out_edges.append({"id": e.id, "source": e.source, "target": e.target, "type": e.type,
                          "status": e.status, "quote": _quote(e.quote, e.pages) if e.quote else None})
    structural = [(n.id, n.section) for n in nodes] + [(s.id, "chapter") for s in scout.sections]
    out_edges += [{"id": edge_id(a, b, "part-of"), "source": a, "target": b, "type": "part-of",
                   "status": "structural", "quote": None} for a, b in structural]
    return {"version": 1, "generator": "noetrix-knowledge-map",
            "source": {"file": scout.vault_rel.replace("\\", "/"), "sha256": scout.sha256,
                       "pages": [scout.page_start, scout.page_end], "title": scout.book_title},
            "chapter": {"title": scout.chapter_title, "template": template.name, "classifier_reason": reason},
            "nodes": out_nodes, "edges": out_edges,
            "canvas": canvas_name(scout.book_title, scout.chapter_title, markers), "run": "run.json"}


def _clip(s: str, room: int) -> str:
    if len(s) <= room:
        return s
    return s[:room - 1].rstrip() + "…" if room >= 1 else ""


def node_body(node: dict, source_file: str) -> str:
    """The canvas text for one node (spec section 6): at most BODY_MAX characters, the
    Source: line never cut. Order of trimming: the summary, then later quotes."""
    title = _clip(" ".join(node["title"].split()), TITLE_MAX)
    summary = " ".join(re.split(r"(?<=[.!?])\s+", " ".join(node["summary"].split()))[:SUMMARY_SENTENCES])
    quotes = [f'> "{" ".join(q["text"].split())}"' for q in node["quotes"]]
    pages = format_pages([tuple(r) for r in node["source_pages"]])
    source = f"Source: {source_file}" + (f" pp. {pages}" if pages else "")

    def build(summ: str, qs: list[str]) -> str:
        return "\n".join([title, summ, *(["", *qs] if qs else []), "", source])

    for n in range(len(quotes), 0, -1) or [0]:
        room = BODY_MAX - len(build("", quotes[:n]))
        if room >= min(len(summary), SUMMARY_FLOOR):
            break
    if room < 0:
        raise ValueError(f"node '{node['id']}': title, quote and Source line alone exceed {BODY_MAX} characters")
    return build(_clip(summary, room), quotes[:n])


def _size(text: str) -> tuple[int, int]:
    lines = sum(len(textwrap.wrap(line, CHARS_PER_LINE)) or 1 for line in text.split("\n"))
    return NODE_W, PAD + lines * LINE_H


def _layers(imp: dict[str, int], pairs: list[tuple[str, str]]) -> list[list[str]]:
    """Layers of node ids. Cycles are broken by ignoring the lowest-importance edge (layout only)."""
    g = nx.DiGraph()
    g.add_nodes_from(sorted(imp))
    g.add_edges_from(sorted(set(pairs)))
    while True:
        try:
            cycle = nx.find_cycle(g)
        except nx.NetworkXNoCycle:
            break
        g.remove_edge(*min(cycle, key=lambda e: (min(imp[e[0]], imp[e[1]]), e)))
    return [sorted(gen, key=lambda i: (-imp[i], i)) for gen in nx.topological_generations(g)]


def render_canvas(graph: dict, layer_edges: tuple[str, ...]) -> dict:
    """JSON Canvas for a map dict. Deterministic; validated with merge_canvas."""
    src = graph["source"]["file"]
    hubs = {n["id"]: n for n in graph["nodes"] if n["kind"] == "hub"}
    sections = [n for n in graph["nodes"] if n["id"].startswith("sec-") and n["kind"] == "hub"]
    members = {s["id"]: [n for n in graph["nodes"] if n.get("section") == s["id"]] for s in sections}
    semantic = [e for e in graph["edges"] if e["status"] != "structural"]

    chapter_text = node_body(hubs["chapter"], src)
    cw, ch = _size(chapter_text)
    canvas_nodes = [{"id": "chapter", "type": "text", "text": chapter_text, "x": 0, "y": 0, "width": cw, "height": ch},
                    {"id": "source-pdf", "type": "file", "file": src, "subpath": f"#page={graph['source']['pages'][0]}",
                     "x": cw + GAP, "y": 0, "width": NODE_W, "height": FILE_H}]
    top = max(ch, FILE_H) + GAP

    groups, texts = [], []
    grid_y, row_h = top, 0
    for i, sec in enumerate(sections):
        col = i % GRID_COLS
        if i and col == 0:
            grid_y += row_h + GAP
            row_h = 0
        gx = col * (GROUP_W + GAP)
        mine = members[sec["id"]]
        imp = {n["id"]: n["importance"] for n in mine}
        pairs = [(e["source"], e["target"]) for e in semantic
                 if e["type"] in layer_edges and e["source"] in imp and e["target"] in imp]
        by_id = {n["id"]: n for n in mine}
        y = grid_y + GROUP_HEAD
        for layer in _layers(imp, pairs):
            for r in range(0, len(layer), GRID_COLS):
                row = layer[r:r + GRID_COLS]
                bodies = {nid: node_body(by_id[nid], src) for nid in row}
                h = max(_size(b)[1] for b in bodies.values())
                for c, nid in enumerate(row):
                    texts.append({"id": nid, "type": "text", "text": bodies[nid],
                                  "x": gx + GAP + c * (NODE_W + GAP), "y": y, "width": NODE_W, "height": h})
                y += h + GAP
        gh = max(y - grid_y, GROUP_HEAD + GAP)
        groups.append({"id": f"group-{sec['id']}", "type": "group", "label": sec["title"],
                       "x": gx, "y": grid_y, "width": GROUP_W, "height": gh})
        row_h = max(row_h, gh)

    edges = [{"id": e["id"], "fromNode": e["source"], "toNode": e["target"],
              "label": e["type"] if e["status"] == "stated" else f"{e['type']} ({e['status']})"}
             for e in semantic]
    canvas = {"nodes": canvas_nodes + groups + texts, "edges": edges}
    merge_canvas(canvas, canvas)
    return canvas
