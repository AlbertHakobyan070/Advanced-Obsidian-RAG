def _closed_port():
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def _write(path, rows):
    """CRLF, like the live files."""
    path.write_bytes(b"".join(json.dumps(r, ensure_ascii=False).encode("utf-8") + b"\r\n" for r in rows))


def _stamped(row):
    return {**row, "metadata": {**row["metadata"], "provenance": "generated"}}


def _nameless(sf):
    """A row with no doc_id: the sparse union keys it chunk_<its record index in its file>."""
    return {"text": "text nameless",
            "metadata": {"source_file": sf, "file_type": "note", "provenance": "authored"}}


