def test_a_row_unstamped_in_one_collection_only_is_stamped_there_alone(world, servers_down):
    for name, rows in JSONLS.items():                       # the JSONLs and ACTIVE already say generated
        _write(world.data / name, [_stamped(r) if r["doc_id"] in IDS else r for r in rows])
    active = world.client.get_collection(ACTIVE)
    got = active.get(ids=IDS, include=["metadatas"])
    active.update(ids=got["ids"], metadatas=[{**m, "provenance": "generated"} for m in got["metadatas"]])
    plan = index_ops.provenance_plan(world.cfg, world.client, RULE)
    assert plan["ids"] == IDS and plan["jsonl"] == {} and plan["chroma"] == {EG2: 2}
    assert plan["files"] == {MAPS: 2}
    before = _dump(world, ACTIVE)
    index_ops.stamp_provenance(world.cfg, world.client, RULE)
    got = world.client.get_collection(EG2).get(ids=IDS, include=["metadatas"])
    assert {m["provenance"] for m in got["metadatas"]} == {"generated"}
    assert _dump(world, ACTIVE) == before
    assert not list(world.data.glob("*.provstamp-*.bak"))   # no JSONL had work, so none was rewritten


