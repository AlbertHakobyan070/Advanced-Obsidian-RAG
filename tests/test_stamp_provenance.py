def _dump(w, name):
    """One collection: id -> (metadata, document, embedding)."""
    g = w.client.get_collection(name).get(include=["metadatas", "documents", "embeddings"])
    return {i: (m, d, tuple(float(x) for x in e))
            for i, m, d, e in zip(g["ids"], g["metadatas"], g["documents"], g["embeddings"])}


def _snapshot(w):
    """Every file outside the Chroma folder (bytes, mtime_ns), and every collection."""
    files = {str(p.relative_to(w.root)): (p.read_bytes(), p.stat().st_mtime_ns)
             for p in sorted(w.root.rglob("*"))
             if p.is_file() and "chroma" not in p.relative_to(w.root).parts}
    return files, {c.name: _dump(w, c.name) for c in w.client.list_collections()}


def _jsonl_provenance(w):
    """doc_id -> the stored provenance in the chunk JSONLs."""
    return {r["doc_id"]: r["metadata"].get("provenance")
            for name in JSONLS
            for r in map(json.loads, (w.data / name).read_text(encoding="utf-8").splitlines())}


def _run(w, *flags):
    import main
    try:
        args = main.build_parser().parse_args(["--config", str(w.config), "stamp-provenance", *flags])
        args.func(args)
    except SystemExit as e:
        return e.code
    return 0


