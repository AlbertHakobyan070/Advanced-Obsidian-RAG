def test_a_fallback_id_shared_across_files_raises_and_writes_nothing(world, servers_down):
    # The reviewer's case: id-less rows on line 1 of two files both fall back to chunk_000000, and
    # chunk_000000 in Chroma is the PRIMARY row; a stamp by that id would write generated onto it
    _write(world.data / "chunks.jsonl", [_nameless(PRIMARY), *JSONLS["chunks.jsonl"]])
    _write(world.data / "maps_chunks.jsonl", [_nameless(MAPS), *JSONLS["maps_chunks.jsonl"]])
    world.client.get_collection(ACTIVE).add(ids=["chunk_000000"], embeddings=[[0.0, 0.0, 1.0]],
                                            documents=["text nameless"], metadatas=[_nameless(PRIMARY)["metadata"]])
    before = _snapshot(world)
    for run in (index_ops.provenance_plan, index_ops.stamp_provenance):
        with pytest.raises(index_ops.ProvenanceStampError, match=r"maps_chunks\.jsonl: line 1: .* has no doc_id"):
            run(world.cfg, world.client, RULE)
    assert _snapshot(world) == before


def test_a_candidate_id_on_a_row_of_another_file_raises_naming_both(world):
    maps = JSONLS["maps_chunks.jsonl"]
    _write(world.data / "maps_chunks.jsonl", [*maps, _rec("p1", MAPS)])        # the primary row came first
    with pytest.raises(index_ops.ProvenanceStampError,
                       match=r"'p1' is in both chunks\.jsonl: line 2 and maps_chunks\.jsonl: line 2") as e:
        index_ops.provenance_plan(world.cfg, world.client, RULE)
    # the chunk JSONLs are primary data: remove the duplicate row, never a whole file
    msg = str(e.value)
    assert "Delete one of the two" not in msg
    assert "refuses and writes nothing" in msg and "Back up both files" in msg
    assert "remove the duplicate row (not the file) by hand" in msg
    _write(world.data / "maps_chunks.jsonl", [*maps, _rec("g1", PRIMARY)])     # the generated row came first
    with pytest.raises(index_ops.ProvenanceStampError,
                       match=r"'g1' is in both chunks\.jsonl: line 1 and maps_chunks\.jsonl: line 2"):
        index_ops.provenance_plan(world.cfg, world.client, RULE)


