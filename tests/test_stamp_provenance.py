def test_apply_stamps_chroma_then_jsonl_and_keeps_everything_else(world, servers_down):
    before = index_ops.provenance_plan(world.cfg, world.client, RULE)["totals"]
    store = {name: _dump(world, name) for name in (ACTIVE, EG2)}
    raw = {name: (world.data / name).read_bytes().splitlines(keepends=True) for name in JSONLS}
    index_ops.stamp_provenance(world.cfg, world.client, RULE)
    for name, old_lines in raw.items():          # the JSONLs are primary data: only the key moves
        new_lines = (world.data / name).read_bytes().splitlines(keepends=True)
        assert len(new_lines) == len(old_lines)
        for old, new in zip(old_lines, new_lines):
            orig = json.loads(old)
            if orig["doc_id"] in IDS:
                assert json.loads(new) == _stamped(orig)
                assert new.endswith(b"\r\n")     # rewrite_jsonl: a replaced line keeps its own terminator
            else:
                assert new == old                # the primary line is byte-identical
    for name in (ACTIVE, EG2):
        got = world.client.get_collection(name).get(ids=IDS, include=["metadatas"])
        assert {m["provenance"] for m in got["metadatas"]} == {"generated"}
        assert all(m["course_code"] == "AIE" for m in got["metadatas"])      # merged, not replaced
        now = _dump(world, name)
        assert now["p1"] == store[name]["p1"]                                 # the primary row is untouched
        assert {i: (d, e) for i, (_, d, e) in now.items()} == \
               {i: (d, e) for i, (_, d, e) in store[name].items()}           # same ids, text and vectors
    assert _jsonl_provenance(world) == {"g1": "generated", "g2": "generated", "p1": "authored"}
    after = index_ops.provenance_plan(world.cfg, world.client, RULE)
    assert after["ids"] == [] and after["totals"] == before
    assert list(world.data.glob("*.provstamp-*.bak"))


def test_a_rerun_heals_a_jsonl_left_unstamped(world, servers_down, fresh_stamps, monkeypatch):
    real, calls = index_ops.rewrite_jsonl, []

    def crash_on_the_second_file(path, fix, **kw):          # the process dies between the two writes
        if calls:
            raise OSError("crashed")
        calls.append(path)
        return real(path, fix, **kw)

    monkeypatch.setattr(index_ops, "rewrite_jsonl", crash_on_the_second_file)
    with pytest.raises(OSError, match="crashed"):
        index_ops.stamp_provenance(world.cfg, world.client, RULE)
    half = index_ops.provenance_plan(world.cfg, world.client, RULE)
    assert half["chroma"] == {}                              # Chroma went first and is complete
    assert half["ids"] == ["g2"] and half["jsonl"] == {"maps_chunks.jsonl": 1}
    assert half["files"] == {MAPS: 1}

    monkeypatch.setattr(index_ops, "rewrite_jsonl", real)
    index_ops.stamp_provenance(world.cfg, world.client, RULE)
    assert index_ops.provenance_plan(world.cfg, world.client, RULE)["ids"] == []
    assert _jsonl_provenance(world) == {"g1": "generated", "g2": "generated", "p1": "authored"}


