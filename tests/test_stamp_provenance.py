def test_cli_needs_dry_run_or_yes_and_refuses_yes_while_a_server_answers(world, monkeypatch, capsys):
    before = _snapshot(world)
    assert _run(world) == 2               # _run wraps parse_args AND args.func in its try (SystemExit 2)
    monkeypatch.setattr(index_ops, "answering_ports", lambda cfg: [8051])
    assert _run(world, "--yes") == 2 and _run(world, "--dry-run") == 0
    out, err = capsys.readouterr()
    assert ":8051 answers" in err
    assert "Maps\\a.md: 2 row(s)" in out and f"jsonl ids {N}" in out and f"bm25 {N}" in out
    assert _snapshot(world) == before
    sidecar = Path(str(world.bm25) + ".meta.json")          # an operator-fixable failure: no traceback
    sidecar.unlink()
    assert _run(world, "--dry-run") == 2
    assert f"ERROR: {sidecar} is missing" in capsys.readouterr().err
    sidecar.write_text("", encoding="utf-8")                # write_sparse_meta is not atomic: a cut-off write
    assert _run(world, "--dry-run") == 2
    assert f"ERROR: {sidecar} is not readable JSON" in capsys.readouterr().err
    sidecar.write_text('{"built_at": "x"}', encoding="utf-8")
    assert _run(world, "--dry-run") == 2
    assert f"ERROR: {sidecar} holds no integer count" in capsys.readouterr().err

    def a_bug(cfg, client, rule):
        raise ValueError("a bug, not the operator's")

    monkeypatch.setattr(index_ops, "provenance_plan", a_bug)
    with pytest.raises(ValueError, match="a bug"):          # anything but ProvenanceStampError keeps its traceback
        _run(world, "--dry-run")


