"""Route-then-cite S1, task 2: every ingest lane stamps `provenance: generated` by the rule.

A file under a provenance.generated_paths prefix, or an agent-instruction file, is
stored as generated by whichever lane reads it (spec §5.2 "Ingest", §7 call 11), so
drop mode can exclude it inside a Chroma query. Stamping is metadata only: text and
doc_ids never change.
"""
import json
import sys
from pathlib import Path

import pytest

from src.ingestion import obsidian_parser, pdf_loader
from src.ingestion.canvas_loader import CanvasLoader
from src.ingestion.code_loader import CodeLoader
from src.ingestion.ipynb_loader import NotebookLoader
from src.ingestion.obsidian_parser import ObsidianParser
from src.ingestion.pdf_loader import PDFLoader
from src.ocr_studio.ingest import build_chunks
from src.ocr_studio.pages import Store
from src.utils.config_loader import Config
from src.utils.provenance import ProvenanceRule, provenance_rule

EXT = {"md": ".md", "pdf": ".pdf", "code": ".py", "ipynb": ".ipynb", "canvas": ".canvas"}
LOADERS = {c.__name__: c for c in (PDFLoader, CodeLoader, NotebookLoader, CanvasLoader)}
# Over every lane's 200-character minimum chunk size.
PROSE = "Plain prose about the garden, repeated to clear the minimum chunk size. " * 4
COURSE = {"course_code": "unknown", "course_name": "unknown", "domain": "general"}


class _Stop(Exception):
    """Raised by a fake parser or loader once it has recorded what it was built with."""


def _rule(tmp_path, **prov) -> ProvenanceRule:
    return provenance_rule(Config({"provenance": prov} if prov else {}, tmp_path))


def _ingest(tmp_path: Path, lane: str, rel: str, rule):
    """One file at vault-relative `rel`, read by `lane` the way that lane's own tests build it."""
    vault = tmp_path / "vault"
    path = vault / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    out = tmp_path / "out.jsonl"
    if lane == "md":
        path.write_text("# Gardening plans\n\n" + PROSE + "\n", encoding="utf-8")
        chunks = ObsidianParser(str(vault), config={"provenance_rule": rule}).parse_file(path)
    elif lane == "pdf":
        loader = PDFLoader(vault_path=vault, output_file=out, scratch_dir=tmp_path,
                           ocr_enabled=False, provenance_rule=rule)
        # The OS form, as the lane passes it (str of a relative_to).
        chunks = loader._chunks_from_md([{"text": PROSE, "metadata": {"page_number": 1}}],
                                        str(Path(rel)), path, COURSE, {})
    elif lane == "code":
        path.write_text("def water(plant):\n    return plant\n\n" * 8, encoding="utf-8")
        chunks = CodeLoader(vault_path=vault, output_file=out, provenance_rule=rule).load_file(path)
    elif lane == "ipynb":
        path.write_text(json.dumps({"cells": [{"cell_type": "markdown", "source": PROSE}]}),
                        encoding="utf-8")
        chunks = NotebookLoader(vault_path=vault, output_file=out, provenance_rule=rule).load_file(path)
    else:
        path.write_text(json.dumps({"nodes": [{"id": "n", "type": "text", "text": PROSE, "x": 0,
                                               "y": 0, "width": 200, "height": 100}], "edges": []}),
                        encoding="utf-8")
        chunks = CanvasLoader(vault_path=vault, output_file=out, min_chunk=10,
                              provenance_rule=rule).load_file(path)
    # An empty result would make the all() assertions below pass vacuously.
    assert chunks, f"the {lane} fixture produced no chunks"
    return chunks


@pytest.mark.parametrize("lane", list(EXT))
def test_a_file_under_a_generated_path_is_stamped_generated(tmp_path, lane):
    chunks = _ingest(tmp_path, lane, "Guides/x" + EXT[lane], _rule(tmp_path, generated_paths=["Guides/"]))
    assert all(c.metadata["provenance"] == "generated" for c in chunks)


@pytest.mark.parametrize("lane,expected", [("md", "authored"), ("pdf", "source"),
                                           ("code", None), ("ipynb", None), ("canvas", None)])
def test_a_file_outside_keeps_its_lane_value(tmp_path, lane, expected):
    chunks = _ingest(tmp_path, lane, "Notes/x" + EXT[lane], _rule(tmp_path, generated_paths=["Guides/"]))
    assert {c.metadata.get("provenance") for c in chunks} == {expected}


def test_an_agent_file_is_stamped_by_name(tmp_path):
    chunks = _ingest(tmp_path, "md", "proj/AGENTS.md", _rule(tmp_path))      # the default names
    assert {c.metadata["provenance"] for c in chunks} == {"generated"}


@pytest.mark.parametrize("lane", list(EXT))
def test_stamping_does_not_change_doc_ids(tmp_path, lane):
    a = _ingest(tmp_path, lane, "Guides/x" + EXT[lane], None)
    b = _ingest(tmp_path, lane, "Guides/x" + EXT[lane], _rule(tmp_path, generated_paths=["Guides/"]))
    assert [c.doc_id for c in a] == [c.doc_id for c in b]
    assert [c.text for c in a] == [c.text for c in b]


@pytest.mark.parametrize("cls", list(LOADERS))
def test_from_config_hands_the_rule_to_the_loader(tmp_path, monkeypatch, cls):
    # PDFLoader.from_config routes the HF and temp caches, and OCR on probes Tesseract
    # (tests/test_lane_exclusions.py does the same).
    monkeypatch.setattr(pdf_loader, "route_caches_to_disk", lambda p: None)
    loader = LOADERS[cls].from_config(Config({"parser": {"vault_path": str(tmp_path)},
                                              "pdf": {"ocr_enabled": False},
                                              "provenance": {"generated_paths": ["Guides/"]}}, tmp_path))
    assert loader.provenance_rule.generated_by_path("Guides/x")


@pytest.mark.parametrize("entry", ["cmd_ingest_md", "parser_main"])
def test_every_md_entry_point_hands_the_rule_to_the_parser(monkeypatch, tmp_path, entry):
    import main
    seen = {}

    def fake_parser(vault, config):
        seen.update(config)
        raise _Stop

    # cmd_ingest_md imports the class inside the function (main.py), so patch the module
    monkeypatch.setattr(obsidian_parser, "ObsidianParser", fake_parser)
    vault = tmp_path / "vault"
    vault.mkdir()
    cfg = tmp_path / "config.yaml"
    cfg.write_text(f"parser:\n  vault_path: {json.dumps(str(vault))}\n"
                   f"provenance:\n  generated_paths: [\"Guides/\"]\n", encoding="utf-8")
    out = str(tmp_path / "x_chunks.jsonl")
    if entry == "cmd_ingest_md":
        args = main.build_parser().parse_args(
            ["--config", str(cfg), "ingest-md", "--include-path", "scope", "--output", out])
        run = lambda: args.func(args)
    else:
        monkeypatch.chdir(tmp_path)                       # load_config() reads ./config.yaml
        # A scoped run with the default --parents-out is refused by the lane guard.
        monkeypatch.setattr(sys, "argv", ["obsidian_parser", str(vault), "-o", out,
                                          "--include-path", "scope", "--parents-out", ""])
        run = obsidian_parser.main

    with pytest.raises(_Stop):
        run()
    assert isinstance(seen["provenance_rule"], ProvenanceRule)
    assert seen["provenance_rule"].generated_by_path("Guides/x.md")      # built from that config


def test_ocr_studio_ingest_builds_its_pdf_loader_with_the_rule(monkeypatch, tmp_path):
    seen = {}

    def fake_loader(**kwargs):
        seen.update(kwargs)
        raise _Stop

    # build_chunks imports PDFLoader inside the function, so patch the module
    monkeypatch.setattr(pdf_loader, "PDFLoader", fake_loader)
    cfg = Config({"provenance": {"generated_paths": ["Guides/"]}}, tmp_path)
    with pytest.raises(_Stop):
        build_chunks(cfg, tmp_path, "Guides/x.pdf", store=Store(tmp_path / "studio"))
    assert seen["provenance_rule"].generated_by_path("Guides/x.pdf")
